package main

import "unicode/utf8"

const (
	glyphRows    = 7
	glyphAdvance = 6 // five glyph columns plus one spacing column
)

// glyphFor returns the bitmap for r. Lowercase letters use the uppercase glyph,
// and unknown runes render as '?'.
func glyphFor(r rune) [glyphRows]string {
	if glyph, ok := lookupGlyph(r); ok {
		return glyph
	}
	return glyphs['?']
}

// supportedGlyph reports whether the bitmap font can draw r.
func supportedGlyph(r rune) bool {
	_, ok := lookupGlyph(r)
	return ok
}

func lookupGlyph(r rune) ([glyphRows]string, bool) {
	if r >= 'a' && r <= 'z' {
		r -= 'a' - 'A'
	}
	glyph, ok := glyphs[r]
	return glyph, ok
}

func textWidth(text string, scale int) int {
	count := utf8.RuneCountInString(text)
	if count == 0 {
		return 0
	}
	return (count*glyphAdvance - 1) * scale
}

